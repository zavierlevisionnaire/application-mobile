-- À exécuter dans Supabase > SQL Editor > New query.
create table if not exists public.articles (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Gabon',
  summary text not null,
  body text not null,
  image_url text,
  published boolean not null default false,
  published_at timestamptz,
  author_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.articles enable row level security;

drop policy if exists "Public can read published articles" on public.articles;
create policy "Public can read published articles"
on public.articles for select
using (published = true or auth.uid() = author_id);

drop policy if exists "Editors can insert articles" on public.articles;
create policy "Editors can insert articles"
on public.articles for insert to authenticated
with check (auth.uid() = author_id);

drop policy if exists "Editors can update own articles" on public.articles;
create policy "Editors can update own articles"
on public.articles for update to authenticated
using (auth.uid() = author_id)
with check (auth.uid() = author_id);

drop policy if exists "Editors can delete own articles" on public.articles;
create policy "Editors can delete own articles"
on public.articles for delete to authenticated
using (auth.uid() = author_id);

